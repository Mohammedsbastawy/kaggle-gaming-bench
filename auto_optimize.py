def get_current_resolution():
    try:
        r = subprocess.run(['xrandr', '--query'], capture_output=True, text=True, timeout=5)
        for line in r.stdout.splitlines():
            if '*' in line:
                return line.strip().split()[0]
    except Exception:
        pass
    return '1280x720'


def set_resolution(res):
    try:
        w, h = res.split('x')
        # Try to set directly first
        r = subprocess.run(['xrandr', '-s', res], capture_output=True, text=True, timeout=5)
        if r.returncode != 0:
            # Create the mode and try again
            cvt = subprocess.run(['cvt', w, h], capture_output=True, text=True, timeout=5)
            for line in cvt.stdout.splitlines():
                if 'Modeline' in line:
                    parts = line.split('"')
                    if len(parts) >= 3:
                        mode_name = parts[1]
                        mode_args = parts[2].strip()
                        subprocess.run(['xrandr', '--newmode', mode_name] + mode_args.split(), check=False, timeout=5)
                        for output in ('screen', 'SCREEN', 'default', 'VGA-0', 'Virtual-1'):
                            subprocess.run(['xrandr', '--addmode', output, mode_name], check=False, timeout=5)
                        subprocess.run(['xrandr', '-s', mode_name], check=False, timeout=5)
        return True
    except Exception as e:
        print(f'Resolution change error: {e}')
        return False


def write_wine_env(preset_key):
    p = PRESETS[preset_key]
    csmt = '1' if p['wine_csmt'] else '0'
    d3d = f"csmt={csmt}"
    if p.get('wine_extra'):
        d3d += ';' + p['wine_extra']

    content = f"""#!/bin/bash
# Auto-generated by 7BZ Auto-Optimizer – preset: {preset_key}
export WINE_D3D_CONFIG="{d3d}"
export MESA_GL_VERSION_OVERRIDE="4.3"
export __GL_SYNC_TO_VBLANK=0
export vblank_mode=0
export WINEDLLOVERRIDES="d3d11,dxgi,d3d9,d3d10core=b"
"""
    WINE_ENV_FILE.parent.mkdir(parents=True, exist_ok=True)
    WINE_ENV_FILE.write_text(content, encoding='utf-8')


def save_settings(preset_key):
    SETTINGS_FILE.parent.mkdir(parents=True, exist_ok=True)
    SETTINGS_FILE.write_text(json.dumps({'preset': preset_key, 'ts': time.time()}, indent=2), encoding='utf-8')


def load_settings():
    try:
        return json.loads(SETTINGS_FILE.read_text(encoding='utf-8')).get('preset', 'high')
    except Exception:
        return 'high'


def inject_keyboard_lock():
    """Inject keyboard lock JS into every Selkies HTML file found on disk."""
    marker = '7BZ Dev Cloud Game: Keyboard Lock'
    patched = []
    search_roots = [Path('/usr/local/lib'), Path('/usr/lib')]
    for root in search_roots:
        if not root.is_dir():
            continue
        for html in root.rglob('index.html'):
            if 'selkies' not in str(html).lower():
                continue
            try:
                text = html.read_text(encoding='utf-8')
                if marker in text:
                    patched.append(f'{html} (already patched)')
                    continue
                if '</head>' in text:
                    html.write_text(text.replace('</head>', KEYBOARD_LOCK_JS + '\n</head>'), encoding='utf-8')
                    patched.append(str(html))
                elif '</body>' in text:
                    html.write_text(text.replace('</body>', KEYBOARD_LOCK_JS + '\n</body>'), encoding='utf-8')
                    patched.append(str(html))
            except Exception as e:
                patched.append(f'{html} (error: {e})')
    return patched


def test_bandwidth():
    """Quick bandwidth measurement (server-side egress estimate)."""
    urls = [
        'https://speed.cloudflare.com/__down?bytes=2000000',
        'https://www.google.com/images/branding/googlelogo/2x/googlelogo_color_272x92dp.png',
    ]
    for url in urls:
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'GameLab/1.0'})
            t0 = time.time()
            with urllib.request.urlopen(req, timeout=8) as resp:
                data = resp.read()
            elapsed = time.time() - t0
            if elapsed > 0.01:
                return (len(data) * 8) / (elapsed * 1_000_000)
        except Exception:
            continue
    return 0.0


def recommend_preset(speed_mbps):
    if speed_mbps >= 30:
        return 'ultra'
    elif speed_mbps >= 15:
        return 'high'
    elif speed_mbps >= 5:
        return 'medium'
    return 'low'


